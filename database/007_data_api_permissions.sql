-- SOCYTO Data API privileges: permissions complement Row Level Security.
-- Run in numeric order after 006_publish_project_progress.sql.
-- This migration intentionally does NOT expose drafts, receipts or client contacts to anon.

grant usage on schema public to authenticated;

revoke all on public.businesses from anon;
revoke all on public.platform_administrators from anon;
revoke all on public.business_members from anon;
revoke all on public.business_subscriptions from anon;
revoke all on public.clients from anon;
revoke all on public.projects from anon;
revoke all on public.project_requirements from anon;
revoke all on public.material_receipts from anon;
revoke all on public.project_publications from anon;
revoke all on public.business_branding from anon;

-- Platform and membership tables: trusted provisioning is required for writes.
revoke all on public.businesses from authenticated;
revoke all on public.platform_administrators from authenticated;
revoke all on public.business_members from authenticated;
revoke all on public.business_subscriptions from authenticated;
grant select on public.businesses, public.platform_administrators,
    public.business_members, public.business_subscriptions to authenticated;

-- Client records: business admins may create contacts, but must NOT self-assign
-- arbitrary auth users as clients. Account linking requires a trusted backend.
revoke all on public.clients from authenticated;
grant select, delete on public.clients to authenticated;
grant insert (business_id, client_name, client_email, client_phone)
    on public.clients to authenticated;
grant update (client_name, client_email, client_phone)
    on public.clients to authenticated;

-- Project FK ensures the chosen client belongs to the same business.
revoke all on public.projects from authenticated;
grant select, insert, update, delete on public.projects to authenticated;

-- Requirements stay private to business admins via existing RLS.
revoke all on public.project_requirements from authenticated;
grant select, insert, delete on public.project_requirements to authenticated;
grant update (requirement_name, tracking_type, effort_score,
    is_completed, required_quantity, completed_quantity, unit_name,
    display_order, updated_at)
    on public.project_requirements to authenticated;

-- Material totals are generated by the database, never client supplied.
revoke all on public.material_receipts from authenticated;
grant select, insert, update, delete on public.material_receipts to authenticated;

-- Clients only receive project publications. Publication writes occur through RPC.
revoke all on public.project_publications from authenticated;
grant select on public.project_publications to authenticated;

-- Firm branding remains platform-managed through save_business_branding RPC.
revoke all on public.business_branding from authenticated;
grant select on public.business_branding to authenticated;

-- The expenditure view must not be exposed to clients. It is intentionally
-- unavailable to authenticated users until an administrator-only RPC exists.
revoke all on public.project_material_expenditure from public, anon, authenticated;

-- Enforce an explicit role check on every privileged RPC; do not grant these to anon.
revoke execute on function public.save_business_branding(
    uuid,text,text,text,text,text,text,text
) from public,anon;
revoke execute on function public.register_business_for_existing_user(
    text,uuid,text
) from public,anon;
revoke execute on function public.publish_project_progress(uuid,uuid,text)
    from public,anon;

grant execute on function public.save_business_branding(
    uuid,text,text,text,text,text,text,text
) to authenticated;
grant execute on function public.register_business_for_existing_user(
    text,uuid,text
) to authenticated;
grant execute on function public.publish_project_progress(uuid,uuid,text)
    to authenticated;
